/* ============================================================
   CUMBRE — VERBOS DÉBILES : les verbes à AFFAIBLISSEMENT (-ir)
   ------------------------------------------------------------
   L'affaiblissement, c'est le e qui devient i et le o qui devient u
   quand la syllabe du radical n'est PAS accentuée. Il ne touche que
   des verbes en -ir, et il frappe là où on ne l'attend pas :
     · indefinido : SEULEMENT él/ellos  → pidió, pidieron · durmió, durmieron
     · gérondif                          → pidiendo · durmiendo · sintiendo
     · subjonctif présent                → pida… / sintamos, durmamos
     · subjonctif imparfait (les 6)      → pidiera… · durmiera… · sintiera…
   Trois familles :
     i  (e→i)        : un seul radical affaibli, jamais de diphtongue.
     ie (e→ie / e→i) : diphtongue sous l'accent, affaiblissement ailleurs.
     ue (o→ue / o→u) : idem (dormir, morir — les deux seuls).
   Formes produites par règle puis relues une à une (y compris les
   accidents d'orthographe : seguir → sigo/sigamos/sigáis, elegir → elijo/elijáis).
   ============================================================ */

